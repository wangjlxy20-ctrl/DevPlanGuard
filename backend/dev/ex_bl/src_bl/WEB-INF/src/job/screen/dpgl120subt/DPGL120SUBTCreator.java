package job.screen.dpgl120subt;

import com.yse.gb.gf.front.html.Input;
import com.yse.gb.gf.front.html.Span;
import com.yse.gb.gf.front.html.Textarea;
import com.yse.gb.util.FormatDate;
import jakarta.enterprise.context.RequestScoped;
import jakarta.inject.Inject;

import com.yse.gb.gf.front.Creator;
import com.yse.gb.gf.front.CreatorException;
import com.yse.gb.gf.front.KeyObj;
import com.yse.gb.gf.front.ValueBean;
import job.entity.Task;
import job.service.SubmissionService;

import java.util.Date;



@RequestScoped
public class DPGL120SUBTCreator extends Creator {

	@Inject
	private SubmissionService submissionService;

	
	@Override
	protected void createValueBean(final KeyObj keyObj, final ValueBean valueBean)
			throws CreatorException, Throwable {
		// Write the code here
		System.out.println("====DPGL120SUBT Creator executed====");

		// SYS TIME
		String now = FormatDate.get_YYYYMMDDhhmmss(new Date(System.currentTimeMillis()));
		valueBean.add(new Span("NMLLBL_NOW_DATE", now));

		//进入其他页面返回时能显示role
		String projectRole = keyObj.get("PROJECT_ROLE");
		String projectId = keyObj.get("PROJECT_ID");
		Input hiddenProjectRole = new Input("NMLTXT_MY_ROLE");
		hiddenProjectRole.setValue(projectRole);
		valueBean.add(hiddenProjectRole);
		Input hiddenProjectId = new Input("NMLTXT_PROJECT_ID");
		hiddenProjectId.setValue(String.valueOf(projectId));
		valueBean.add(hiddenProjectId);
		// 文件上传隐藏域（值由前端 JS 写入，这里只注册组件让框架接管）
		valueBean.add(new Input("NMLTXT_DELIVERABLE_FILE"));
		// TASK_ID brought from the member task list
		String taskId = keyObj.get("TASK_ID");
		String taskType = keyObj.get("TASK_TYPE");
		System.out.println(">>>>DPGL120SUBT got TASK_ID: " + taskId);

		if (taskId == null || taskId.trim().isEmpty()) {
			return;
		}

		// LOAD TASK INFO（findTaskById 用 SELECT *，含 parent_id / test_plan / test_case_design）
		// 查询条件实体（只带 task_id）
		Task condition = new Task();
		condition.setTaskId(Integer.valueOf(taskId.trim()));

		Task task = submissionService.findTaskById(condition);
		if (task == null) {
			return;
		}

		String taskCode = String.valueOf(task.getTaskCode());
		String taskName = String.valueOf(task.getTaskName());
		String taskDescription = String.valueOf(task.getDescription());

		// ===== 关键判断：parent_id 有值 = 系统自动生成；为空 = 手动创建 =====
		Integer parentIdObj = task.getParentId();
		String parentId = parentIdObj == null ? "" : String.valueOf(parentIdObj).trim();
		boolean isAutoGenerated = parentId.length() > 0 && !"null".equals(parentId);
		System.out.println("TASK SOURCE: parent_id=" + parentId
				+ ", isAutoGenerated=" + isAutoGenerated);
		// ===== 按 HTML 表单顺序构建组件 =====

		// 1) Task
		valueBean.add(new Span("NMLLBL_TASK_CODE", taskCode));
		valueBean.add(new Span("NMLLBL_TASK_NAME", taskName));

		// 2) Test Plan（条件：空可编辑 / 回显只读）
		if (isAutoGenerated) {
			// 系统自动生成：空、可编辑
			valueBean.add(new Textarea("NMLTXA_TEST_PLAN"));
		} else {
			// 手动创建：回显已有值、只读
			Textarea testPlan = new Textarea("NMLTXA_TEST_PLAN",
					nullToEmpty(task.getTestPlan()));
			testPlan.setReadOnly(true);
			valueBean.add(testPlan);
		}

		// 3) Task Type
		valueBean.add(new Span("NMLLBL_TASK_TYPE", taskType == null ? "" : taskType));

		// 4) TASK DESCRIPTION
		valueBean.add(new Span("NMLLBL_TASK_DESC", taskDescription));

		// 5) Test Case Design（条件：空可编辑 / 回显只读）
		if (isAutoGenerated) {
			// 系统自动生成：空、可编辑
			valueBean.add(new Textarea("NMLTXA_TEST_CASE_DESIGN"));
		} else {
			// 手动创建：回显已有值、只读
			Textarea testCaseDesign = new Textarea("NMLTXA_TEST_CASE_DESIGN",
					nullToEmpty(task.getTestCaseDesign()));
			testCaseDesign.setReadOnly(true);
			valueBean.add(testCaseDesign);
		}

		// HIDDEN task_id for submit
		Input hiddenTid = new Input("NMLTXT_TASK_ID");
		hiddenTid.setValue(taskId);
		valueBean.add(hiddenTid);
	}

	
	private String nullToEmpty(Object o) {
		return o == null ? "" : String.valueOf(o);
	}

}

